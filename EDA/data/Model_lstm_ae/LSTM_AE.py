def reconstruction_to_risk(
    reconstruction_errors,
    reference_errors
):
    reconstruction_errors = np.asarray(
        reconstruction_errors
    )

    reference_errors = np.asarray(
        reference_errors
    )

    risk_scores = np.searchsorted(
        reference_errors,
        reconstruction_errors,
        side="right"
    ) / len(reference_errors)

    return risk_scores

