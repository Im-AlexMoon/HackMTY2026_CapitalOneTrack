def create_sequences(x, customer_ids, timesteps=10):
    sequences = []

    temp = x.copy()
    temp["customer_id"] = customer_ids

    for customer_id, group in temp.groupby("customer_id"):
        features = group.drop(columns="customer_id").values

        if len(features) < timesteps:
            continue

        for i in range(len(features) - timesteps + 1):
            sequence = features[i:i + timesteps]
            sequences.append(sequence)

    return np.array(sequences)

