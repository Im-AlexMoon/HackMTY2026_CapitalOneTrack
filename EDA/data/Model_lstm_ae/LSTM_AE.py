def create_sequences_with_labels(x, y, customer_ids, timesteps=10):
    sequences = []
    labels = []

    temp = x.copy()
    temp["customer_id"] = customer_ids
    temp["target"] = y

    for customer_id, group in temp.groupby("customer_id"):
        features = group.drop(
            columns=["customer_id", "target"]
        ).values

        targets = group["target"].values

        if len(features) < timesteps:
            continue

        for i in range(len(features) - timesteps + 1):
            sequences.append(
                features[i:i + timesteps]
            )

            labels.append(
                targets[i + timesteps - 1]
            )

    return np.array(sequences), np.array(labels)

